// 「ログインし直したばかり」を要求する操作の判定 (2026-11 のセキュリティ監査 M-6)。
//
// セッション Cookie を持っているだけで通る操作のうち、**盗まれたセッションの
// 被害を永続化させるもの**には、セッションの有無とは別に「直近にログインした
// 本人か」を要求する:
//
//   - パスキーの登録 … 盗んだセッションで自分の認証器を足せば、持ち主が
//     ログアウトしても正規のパスキーを消しても、自分の鍵で入り直せる (バックドア)
//   - パスキーの削除 … 正規の鍵を全部消す (締め出しにはならないが嫌がらせ)
//   - 鍵束 (シークレットの包み) の初回設定と上書き … 持ち主が解錠できなくなる
//   - 他の端末のセッション失効 … 盗んだ側が持ち主を締め出すのに使える
//
// 「直近」の判定は**セッションの発行時刻**で行う。再認証の UI を別に作らず、
// 「ログインし直す = 新しいセッションが発行される」をそのまま使う:
//   - パスワード (Basic) … ブラウザが資格情報を覚えていれば /login で黙って
//     発行し直されるので、本人には一手間で済む。盗んだ側は資格情報を持たない
//   - パスキー … Face ID をもう一度
// 発行時刻は sessions.created_at (延長で動く expires_at とは別) を見る。
//
// この階層は純粋な計算だけ。route 側の門は route/guard.ts の guardRecentLogin。

// ログインからこの時間以内なら「直近」。10 分あれば設定画面での一連の操作
// (登録 → 鍵束の設定) に足り、盗んだセッションが古いものである限りは閉じられる
export const RECENT_LOGIN_MAX_AGE_MS = 10 * 60 * 1000

// 断るときの文言。画面はこれを見て「ログインし直す」導線を出す
// (components/auth/PasskeyManager.tsx)
export const REAUTH_REQUIRED_MESSAGE =
  'この操作はログインし直してから 10 分以内だけ行えます。パスワードかパスキーでログインし直してください'

// createdAt が無い (古い呼び出し元・照合に createdAt を含めていない差し替え) は
// 「直近ではない」に倒す。欠落が「いつでも通る」側に倒れてはいけない
export function isRecentLogin(createdAt: Date | undefined, now: Date = new Date()): boolean {
  if (createdAt === undefined) {
    return false
  }
  return now.getTime() - createdAt.getTime() <= RECENT_LOGIN_MAX_AGE_MS
}
