// ZIP 1 ファイルの上限 (docs/28-エクスポート計画.md §3)。
//
// **クライアントとサーバの両方から import する**ためにここへ切り出す
// (lib/enex/limits.ts と同じ理由)。server 専用の依存を持つファイルに置くと、
// 取り込み画面 (NotesImporter) から読めない。

// アップロードできる .zip の大きさ。
//
// **エッジ (deploy/nginx/qr.tommie.jp.conf の /api/import、および compose の
// proxy プロファイル用 Caddyfile) がこの値を賄っている**ので、変えるときは
// あちらも一緒に変えること。片方だけ上げても、アプリに届く前に 413 で切られて
// ブラウザには "Load failed" としか出ない (サーバの JSON エラーは届かない)。
//
// **この大きさを受けられるのは取り込みが本文をメモリに溜めないから**
// (lib/zip/readZip.ts)。入口のバイト列も添付も抱えずに流すので、載るのは
// 「いま保存している添付 1 件」と「ノート本文の合計」(下の上限) だけになる。
// 素直に formData() で受けていた頃はこの値を上げられなかった — 本文全体と
// その複製で入口の 2 倍が載っていた。
export const MAX_ZIP_BYTES = 500 * 1024 * 1024

// 展開後の合計の上限 (ZIP 爆弾よけ)。
//
// **入口が 500MB でも出口は無限になりうる**のが ZIP 爆弾で、ゼロ埋めの
// ファイルは 1000 倍に膨らむ。一方、本物の書き出しは中身の大半が圧縮済みの
// 添付 (jpg/webp/mp4) を無圧縮で入れてあるので、展開しても入口とほとんど
// 変わらない。2 倍まで許せば正規のファイルは全部通り、爆弾は止まる。
//
// これが縛るのは**メモリではなく仕事の量** (DB へ書く総量)。載る量のほうは
// 上の MAX_ZIP_BYTES のコメントのとおり、流しながら捨てることで抑えている。
export const MAX_ZIP_TOTAL_BYTES = 2 * MAX_ZIP_BYTES

// 展開後の 1 ファイルの上限。**DB に入りうる最大**である CLI 取り込みの
// 添付上限 (lib/enex/limits.ts の MAX_CLI_ATTACHMENT_BYTES = 50MB) と揃える。
//
// かつてここは動画の Web アップロード上限 (30MB) だったが、それだと CLI から
// 入った 30MB 超の添付が「書き出せるのに戻せない」— 実測でも 11〜12MB の
// iPhone 写真 3 枚が旧値 (画像 10MB) に弾かれた。**書き出しに入りうるもの
// すべてが戻ること**が往復の要件なので、上限は入口 (Web) ではなく器 (DB) に
// 合わせる。
export const MAX_ZIP_FILE_BYTES = 50 * 1024 * 1024

// 取り込みの途中で抱えておくノート本文の合計。
//
// 添付は届いたそばから DB へ書いて捨てられるが、**ノートは全部の添付が
// 入り終わるまで待たせる** (先に入れると、取り込んだ直後の一覧で画像が割れて
// 見える)。つまりノート本文だけは溜まるので、ここで頭を抑える。
//
// 1 件は最大 32,000 文字 (MAX_TEXT_LENGTH) なので、64MB は上限いっぱいの
// ノートでも数百件ぶん。実データのノートは 1KB 前後なので、まず当たらない。
export const MAX_ZIP_NOTE_BYTES = 64 * 1024 * 1024

// ZIP に入っていてよい項目数 (ノートと添付の合計)。
//
// 細工したファイルで延々とループを回されないための安全弁 (ENEX の
// MAX_NOTES_PER_IMPORT と同じ役割)。
//
// **かつてここは 2000 だった** — fflate の Unzip が項目ごとに再帰するため、
// 3500 件で `RangeError: Maximum call stack size exceeded` になったからである。
// これは**入力を 1 回で push していたせい**で、細切れに push する形
// (readZip.ts) に変えると 30000 件でも通ることを実測した。上限を実装の都合で
// 決める必要がなくなったので、「個人のノートの総数として現実的な上限」に置く。
export const MAX_ZIP_ENTRIES = 20000

export function zipTooLargeMessage(actualBytes: number): string {
  const actual = (actualBytes / 1024 / 1024).toFixed(1)
  const limit = MAX_ZIP_BYTES / 1024 / 1024
  return (
    `ファイルが大きすぎます (${actual}MB / 上限 ${limit}MB)。` +
    'ノートを分けて書き出してから取り込んで下さい'
  )
}
