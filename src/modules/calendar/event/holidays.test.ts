const expected = CAO.trim()
  .split('\n')
  .map((line) => {
    const [date, name] = line.split(' ')
    return { date, name }
  })

describe('holidaysBetween', () => {
  test('2016〜2027 年の祝日・休日の日付が内閣府の表と一致する', () => {
    const got = holidaysBetween('2016-01-01', '2028-01-01').map((h) => h.date)
    expect(got).toEqual(expected.map((h) => h.date))
  })

  test('祝日の名前が内閣府の表と一致する (「休日」の行を除く)', () => {
    const got = new Map(holidaysBetween('2016-01-01', '2028-01-01').map((h) => [h.date, h.name]))
    for (const { date, name } of expected) {
      if (name.includes('休日') || name.includes('（')) {
        continue
      }
      expect([date, got.get(date)]).toEqual([date, name])
    }
  })

  test('振替休日と国民の休日はそう名付ける', () => {
    expect(holidayName('2026-05-06')).toBe('振替休日')
    expect(holidayName('2026-09-22')).toBe('国民の休日')
  })

  test('範囲は半開区間 (終わりの日を含まない)', () => {
    expect(holidaysBetween('2026-11-01', '2026-11-23')).toEqual([{ date: '2026-11-03', name: '文化の日' }])
  })

  test('平日・範囲外の年は祝日ではない', () => {
    expect(holidayName('2026-11-04')).toBeNull()
    expect(holidayName('2100-01-01')).toBeNull()
  })
})
